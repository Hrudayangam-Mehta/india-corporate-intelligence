import type { Company } from '../types';

// Helper to convert raw data to Company type
function makeCompany(
  id: string,
  name: string,
  symbol: string,
  sector: string,
  industry: string,
  marketCap: number,
  lat: number,
  lng: number,
  city: string,
  state: string,
  exchanges: ('NSE' | 'BSE')[]
): Company {
  return {
    id,
    name,
    isin: '',
    nseSymbol: exchanges.includes('NSE') ? symbol : undefined,
    bseCode: exchanges.includes('BSE') ? symbol : undefined,
    sector,
    industry,
    marketCap,
    hqLocation: { lat, lng, city, state },
    incorporated: '',
    listingStatus: 'listed',
    exchanges,
    lastUpdated: '',
    dataSource: [],
  };
}

